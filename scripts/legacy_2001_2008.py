def task(year, number, text, topic, difficulty, page, *, display_number=None, image=None):
    suffix = display_number or str(number)
    task_id = f"{year}-{number}"
    if display_number and not display_number.isdigit():
        task_id += "p"
    item = {
        "id": task_id,
        "year": year,
        "date": DATES[year],
        "number": number,
        "title": f"Задача {year}.{suffix}",
        "text": text,
        "topic": topic,
        "difficulty": difficulty,
        "pdf": f"pdfs/{PDFS[year]}#page={page}",
    }
    if display_number:
        item["displayNumber"] = display_number
    if image:
        item["image"] = image
    return item


