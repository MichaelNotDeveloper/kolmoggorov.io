def read_tasks() -> list[dict]:
    raw = DATA_FILE.read_text(encoding="utf-8").strip()
    prefix = "window.KOLMOGGOROV_DATA = "
    if not raw.startswith(prefix) or not raw.endswith(";"):
        raise RuntimeError("Unexpected tasks-data.js format")
    return json.loads(raw[len(prefix):-1])["tasks"]


def normalize_text(text: str) -> str:
    text = text.replace("/emdash.cyr", "—")
    text = re.sub(r"-\n(?=[а-яёa-z])", "", text, flags=re.I)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def edition_text(reader: PdfReader, start: int, end: int) -> str:
    return "\n".join((reader.pages[index - 1].extract_text() or "") for index in range(start, end))


def solution_chunk(text: str, number: int) -> str:
    patterns = [
        rf"(?mi)^\s*Задача\s+{number}(?:\.|(?=\s|$))\s*",
        rf"(?mi)^\s*Problem\s+\d+\.{number}\.\s*",
        rf"(?mi)^\s*{number}\.\s*(?:\([^\n)]*\))?\s*",
    ]
    starts = [match for pattern in patterns if (match := re.search(pattern, text))]
    if not starts:
        return ""
    start = min(starts, key=lambda match: match.start()).start()
    following = []
    for pattern in (
        rf"(?mi)^\s*Задача\s+{number + 1}(?:\.|(?=\s|$))\s*",
        rf"(?mi)^\s*Problem\s+\d+\.{number + 1}\.\s*",
        rf"(?mi)^\s*{number + 1}\.\s*(?:\([^\n)]*\))?\s*",
    ):
        match = re.search(pattern, text[start + 1:])
        if match:
            following.append(start + 1 + match.start())
    end = min(following) if following else len(text)
    chunk = text[start:end]
    solution = re.split(r"(?i)Решение\s*[\.:]", chunk, maxsplit=1)
    return normalize_text(solution[-1])


def technique_for(task: dict, chunk: str) -> tuple[str, str, list[str]]:
    haystack = f"{task['text']} {chunk}".lower()
    matches = []
    for pattern, label, hint in TECHNIQUES:
        if re.search(pattern, haystack, re.I):
            matches.append((label, hint))
    if matches:
        labels = [label for label, _ in matches[:3]]
        return labels[0], matches[0][1], labels
    topic = task.get("topic", "Общая теория вероятностей")
    return topic, TOPIC_FALLBACKS.get(topic, TOPIC_FALLBACKS["Общая теория вероятностей"]), []


def inferred_difficulty(task: dict, chunk: str) -> tuple[str, str]:
    words = len(re.findall(r"[A-Za-zА-Яа-яЁё]+", chunk))
    existing_rank = {"easy": 1, "medium": 2, "hard": 3, "medal": 4}.get(task.get("difficulty"), 2)
    if words < 15:
        rank = existing_rank
    elif words < 80:
        length_rank = 1
        rank = round(0.6 * length_rank + 0.4 * existing_rank)
    elif words < 180:
        length_rank = 2
        rank = round(0.6 * length_rank + 0.4 * existing_rank)
    elif words < 380:
        length_rank = 3
        rank = round(0.6 * length_rank + 0.4 * existing_rank)
    else:
        length_rank = 4
        rank = round(0.6 * length_rank + 0.4 * existing_rank)
    if ADVANCED.search(f"{task['text']} {chunk}"):
        rank = max(rank, 3)
    labels = {1: "easy", 2: "medium", 3: "hard", 4: "medal"}
    descriptions = {
        1: "официальный разбор короткий и использует один стандартный приём",
        2: "нужно распознать основной приём и аккуратно довести вычисление",
        3: "решение содержит несколько существенных переходов или требует развитой техники",
        4: "официальный разбор длинный либо опирается на продвинутый аппарат",
    }
    return labels[rank], descriptions[rank]


def append_topics(base: list[str], additions: list[str]) -> list[str]:
    result = []
    for item in [*base, *additions]:
        if item and item not in result:
            result.append(item)
    return result[:4]


def main(solution_dir: Path) -> None:
    tasks = read_tasks()
    study = json.loads(STUDY_FILE.read_text(encoding="utf-8"))
    PDF_DEST.mkdir(parents=True, exist_ok=True)

    readers = {}
    texts = {}
    for year, (filename, start, end) in SOURCES.items():
        source = solution_dir / filename
        if not source.exists():
            raise FileNotFoundError(source)
        target = PDF_DEST / filename
        shutil.copy2(source, target)
        reader = PdfReader(source)
        readers[year] = reader
        texts[year] = edition_text(reader, start, min(end, len(reader.pages) + 1))

    by_year = {}
    for task in tasks:
        by_year.setdefault(task["year"], []).append(task)

    attached = 0
    for year, year_tasks in by_year.items():
        if year not in SOURCES:
            continue
        year_tasks.sort(key=lambda item: (item["number"], item["id"]))
        pages = PAGES[year]
        if len(pages) != len(year_tasks):
            raise RuntimeError(f"Page map mismatch for {year}: {len(pages)} != {len(year_tasks)}")
        filename = SOURCES[year][0]
        for task, page in zip(year_tasks, pages):
            existing = study["tasks"].get(task["id"], {})
            chunk = solution_chunk(texts[year], task["number"])
            technique, generated_hint, inferred_topics = technique_for(task, chunk)
            difficulty, difficulty_reason = inferred_difficulty(task, chunk)

            if task["id"] in LEGACY_HINTS:
                generated_hint = LEGACY_HINTS[task["id"]]
                difficulty = LEGACY_DIFFICULTY[task["id"]]

            if year == 2026 and existing:
                generated_hint = existing.get("hint", generated_hint)
                difficulty = existing.get("difficulty", difficulty)
                topics = existing.get("topics", [task["topic"]])
                solution = existing.get("solution", "")
                answer = existing.get("answer", "")
                analysis = existing.get("analysis", {})
            else:
                topics = append_topics([task.get("topic", "")], inferred_topics)
                solution = (
                    f"Официальное решение задачи {task['year']}.{task.get('displayNumber', task['number'])} "
                    f"приведено ниже на странице {page}. Сохранена оригинальная вёрстка PDF, "
                    "чтобы формулы, схемы и обозначения отображались без ошибок распознавания."
                )
                answer = ""
                analysis = {
                    "keyIdeas": [f"Основной приём: {technique}."],
                    "alternativeApproaches": [],
                    "pitfalls": ["Подсказка показывает только первый методический шаг; полный разбор раскрывается отдельно."],
                    "difficultyRationale": f"Оценка пересмотрена по официальному решению: {difficulty_reason}.",
                }

            study["tasks"][task["id"]] = {
                "difficulty": difficulty,
                "topics": topics,
                "answer": answer,
                "hint": generated_hint,
                "solution": solution,
                "officialSolution": {
                    "pdf": f"pdfs/solutions/{filename}",
                    "page": page,
                    "label": f"Официальное решение · стр. {page}",
                },
                "analysis": analysis,
            }
            attached += 1

    study["version"] = 2
    study["updatedAt"] = "2026-09-23"
    study["coverage"] = {
        "officialSolutions": attached,
        "totalTasks": len(tasks),
        "missingYears": [2019],
    }
    STUDY_FILE.write_text(json.dumps(study, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Attached official solutions to {attached} of {len(tasks)} tasks")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("solution_dir", type=Path)
    main(parser.parse_args().solution_dir)
