def clean_condition(text: str) -> str:
    text = text.strip()
    text = re.sub(r"[ \t]+\n", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text


source = DATA_FILE.read_text(encoding="utf-8")
match = re.fullmatch(r"window\.KOLMOGGOROV_DATA = (.*);\s*", source, re.DOTALL)
if not match:
    raise SystemExit("Unexpected tasks-data.js format")

payload = json.loads(match.group(1))
existing_ids = {task["id"] for task in payload["tasks"]}
payload["tasks"].extend(task for task in ADDITIONS if task["id"] not in existing_ids)
tasks_by_id = {task["id"]: task for task in payload["tasks"]}

for task_id, text in CONDITIONS.items():
    if task_id not in tasks_by_id:
        raise SystemExit(f"Unknown task id: {task_id}")
    tasks_by_id[task_id]["text"] = clean_condition(text)

for task in payload["tasks"]:
    display_number = task.get("displayNumber", str(task["number"]))
    task["title"] = f"Задача {task['year']}.{display_number}"

